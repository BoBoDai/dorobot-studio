#!/usr/bin/env python3
"""Build the requested symmetric Nano simulation arm from the right-arm model.

This is a local model override, not a claim that the source CAD or physical robot
has a mirrored assembly. The source CAD uses two same-handed arm instances.
Reflection is across base_link Y=0, keeping every link frame right-handed:
T_left = S T_right S, mesh_left = S mesh_right, axis_left = -S axis_right.
Equal joint coordinates then produce mirrored geometry throughout the chain.
"""

from __future__ import annotations

import argparse
import copy
import hashlib
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

import numpy as np

MODEL = Path(__file__).resolve().parents[1] / "data/adora_nano"
S = np.array([1.0, -1.0, 1.0])
STL = np.dtype(
    [("normal", "<f4", 3), ("vertices", "<f4", (3, 3)), ("attribute", "<u2")]
)


def numbers(value):
    return np.fromstring(value, sep=" ")


def formatted(value):
    return " ".join(f"{v:.14g}" if v else "0" for v in value)


def reflect_attribute(element, name, signs, default=None):
    value = element.get(name, default)
    if value is not None:
        element.set(name, formatted(numbers(value) * signs))


def rename(element):
    for node in element.iter():
        for key, value in list(node.attrib.items()):
            if key in ("name", "link", "mesh") and value.startswith("right_"):
                node.set(key, "left_" + value[6:])


def mirror_stl(source, target):
    data = source.read_bytes()
    count = int.from_bytes(data[80:84], "little")
    if len(data) != 84 + count * STL.itemsize:
        raise ValueError(f"Not a binary STL: {source}")
    triangles = np.frombuffer(data, dtype=STL, offset=84).copy()
    triangles["vertices"] *= S
    triangles["normal"] *= S
    # Reflection reverses handedness. Restore outward triangle winding.
    triangles["vertices"] = triangles["vertices"][:, [0, 2, 1], :]
    target.write_bytes(
        b"Nano local mirrored arm; generated by tools/mirror_nano_arm.py".ljust(
            80, b" "
        )
        + data[80:84]
        + triangles.tobytes()
    )


def replace_block(text, element):
    pattern = (
        rf'  <{element.tag} name="{re.escape(element.get("name"))}".*?</{element.tag}>'
    )
    ET.indent(element, space="  ", level=1)
    block = "  " + ET.tostring(element, encoding="unicode").rstrip()
    text, count = re.subn(pattern, lambda _: block, text, count=1, flags=re.S)
    if count != 1:
        raise ValueError(f"Missing existing {element.tag}: {element.get('name')}")
    return text


def build_urdf(folder):
    path = folder / "adora_nano.urdf"
    text = path.read_text()
    root = ET.fromstring(text)
    meshes = {}
    for original in root.findall("link") + root.findall("joint"):
        if not original.get("name").startswith("right_"):
            continue
        element = copy.deepcopy(original)
        rename(element)
        for origin in element.iter("origin"):
            reflect_attribute(origin, "xyz", S)
            reflect_attribute(origin, "rpy", -S)
        for axis in element.iter("axis"):
            # Angular velocity is an axial vector, not a position vector.
            reflect_attribute(axis, "xyz", -S)
        for inertia in element.iter("inertia"):
            for key in ("ixy", "iyz"):
                inertia.set(key, formatted([-float(inertia.get(key))]))
        for mesh in element.iter("mesh"):
            source = mesh.get("filename")
            target = source.replace("/right_", "/left_")
            if source == target:
                raise ValueError(f"Expected side-specific mesh: {source}")
            mesh.set("filename", target)
            meshes[target] = source
        text = replace_block(text, element)
    for target, source in meshes.items():
        mirror_stl(folder / source, folder / target)
    path.write_text(text)
    return meshes


def build_floating(folder):
    path = folder / "adora_nano_floating.xml"
    tree = ET.parse(path)
    base = tree.getroot().find("./worldbody/body[@name='base_link']")
    old = base.find("body[@name='left_shoulder']")
    mirrored = copy.deepcopy(base.find("body[@name='right_shoulder']"))
    rename(mirrored)
    for node in mirrored.iter():
        reflect_attribute(node, "pos", S)
        reflect_attribute(node, "quat", [1, -1, 1, -1])
        if node.tag == "joint":
            reflect_attribute(node, "axis", -S, "0 0 1")
    index = list(base).index(old)
    base.remove(old)
    base.insert(index, mirrored)
    ET.indent(tree, space="  ")
    tree.write(path, encoding="unicode")
    with path.open("a") as file:
        file.write("\n")


def build(folder):
    meshes = build_urdf(folder)
    build_floating(folder)
    path = folder / "provenance.json"
    provenance = json.loads(path.read_text())
    provenance.pop("mount_overrides", None)
    provenance["studio_urdf_sha256"] = hashlib.sha256(
        (folder / "adora_nano.urdf").read_bytes()
    ).hexdigest()
    provenance["adaptation"] = (
        "Relative mesh paths; Studio colours and split base surfaces; local symmetric "
        "simulation assembly: left chain reflected from right across base_link Y=0. "
        "Source CAD has same-handed arms. Joint names and limits retained; left "
        "frames, axes, meshes and inertia mirrored. Not hardware calibration."
    )
    provenance["arm_symmetry_override"] = dict(
        plane="base_link Y=0 (XZ plane)",
        reference="right arm",
        local_reflection=[1, -1, 1],
        angular_axis_reflection=[-1, 1, -1],
        convention="equal left/right joint values produce mirrored poses",
        source_cad="two identically oriented instances separated by 460 mm",
        hardware_validated=False,
        supersedes="left mount yaw +180 degrees",
        generator="tools/mirror_nano_arm.py",
        floating_xml_updated=True,
        mirrored_meshes=len(meshes),
    )
    path.write_text(json.dumps(provenance, indent=2) + "\n")
    print(
        f"Mirrored the left chain and {len(meshes)} meshes; regenerated floating XML and provenance."
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model-directory", type=Path, default=MODEL)
    build(parser.parse_args().model_directory)
